// Dev-time build: bundles src/main.js (+three) and inlines everything into ONE html file.
//   node tools/build.mjs                -> ./index.html (full game, minified)
//   node tools/build.mjs --dev world    -> <scratch>/dev/world.html (only listed modules real, others stubbed)
//   node tools/build.mjs --dev leaves,world --out /path/x.html
//   (every build regenerates src/assets.gen.js and hd/*.js from assets/)
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
const SCRATCH = process.env.GF_SCRATCH || '/tmp/claude-0/-home-user-261123/bf91c04a-a22b-5ecb-ae38-739d55f80253/scratchpad';
const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i < 0 ? null : (args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : true); };

let esbuild;
for (const base of [ROOT, path.join(SCRATCH, 'tools'), process.cwd()]) {
  try { esbuild = createRequire(path.join(base, 'x.js'))('esbuild'); break; } catch (e) {}
}
if (!esbuild) { console.error('esbuild not found. Run: npm i esbuild   (in ' + path.join(SCRATCH, 'tools') + ')'); process.exit(1); }

const MODULES = ['audio', 'world', 'leaves', 'fire', 'potato', 'story'];

// Start-up textures: small previews (assets/preview/*.webp, made by tools/previews.py) are inlined into index.html;
// the full images go to hd/<name>.js (one script each, streamed in by main.js after the first frame, in this order).
// --dev builds inline the full images instead (the dev html lives in the scratchpad, away from hd/).
const HD_ORDER = ['backdrop', 'ground', 'leaves', 'leaflitter', 'branch', 'bark', 'stone', 'zaru', 'weave', 'potato_skin',
  'potato_roast', 'ash', 'flesh_yellow', 'flesh_purple', 'flesh_orange'];
function genAssets(dev) {
  const dir = path.join(ROOT, 'assets');
  const uri = (f) => `data:${f.endsWith('.png') ? 'image/png' : f.endsWith('.jpg') ? 'image/jpeg' : 'image/webp'};base64,${fs.readFileSync(f).toString('base64')}`;
  const names = fs.readdirSync(dir).filter((f) => /\.(webp|png|jpg)$/.test(f) && !f.startsWith('fallback'))
    .map((f) => [f.replace(/\.\w+$/, ''), path.join(dir, f)]);
  const order = (n) => { const i = HD_ORDER.indexOf(n); return i < 0 ? 99 : i; };
  names.sort((a, b) => order(a[0]) - order(b[0]) || (a[0] < b[0] ? -1 : 1));
  const out = ['// GENERATED by tools/build.mjs. Do not edit.', 'export const PREVIEW = {'];
  const hd = [];
  if (!dev) fs.mkdirSync(path.join(ROOT, 'hd'), { recursive: true });
  for (const [n, full] of names) {
    const pv = path.join(dir, 'preview', path.basename(full));
    const usePv = !dev && fs.existsSync(pv);
    out.push(`  ${JSON.stringify(n)}: "${uri(usePv ? pv : full)}",`);
    if (!usePv) continue;
    const js = `window.__gfHD&&__gfHD(${JSON.stringify(n)},"${uri(full)}");\n`;
    fs.writeFileSync(path.join(ROOT, 'hd', n + '.js'), js);
    hd.push(`  ${JSON.stringify(n)}: "${crypto.createHash('sha1').update(js).digest('hex').slice(0, 8)}",`);
  }
  out.push('};', 'export const HD = {', ...hd, '};', '');
  fs.writeFileSync(path.join(SRC, 'assets.gen.js'), out.join('\n'));
}

const dev = flag('--dev');
genAssets(!!dev);
const real = dev ? String(dev === true ? '' : dev).split(',').filter(Boolean) : MODULES;
const stubPlugin = {
  name: 'stub',
  setup(b) {
    b.onResolve({ filter: /^\.\/(audio|world|leaves|fire|potato|story)\.js$/ }, (a) => {
      const name = a.path.slice(2, -3);
      if (dev && !real.includes(name)) return { path: path.join(SRC, 'stub.js') };
      return null;
    });
  },
};

const res = await esbuild.build({
  entryPoints: [path.join(SRC, 'main.js')],
  bundle: true, format: 'iife', write: false, minify: !dev, target: ['safari14.1', 'chrome90'],
  alias: { three: path.join(SRC, 'vendor/three.module.min.js') },
  define: { __DEV__: dev ? 'true' : 'false', __DEV_MODULES__: JSON.stringify(real) },
  plugins: [stubPlugin], logLevel: 'warning', legalComments: 'none',
});
let js = res.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
let html = fs.readFileSync(path.join(SRC, 'shell.html'), 'utf8');
if (!html.includes('/*__BUNDLE__*/')) { console.error('shell.html must contain /*__BUNDLE__*/'); process.exit(1); }
html = html.replace('/*__BUNDLE__*/', () => js);
let out = flag('--out');
if (!out || out === true) out = dev ? path.join(SCRATCH, 'dev', (real[real.length - 1] || 'engine') + '.html') : path.join(ROOT, 'index.html');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, html);
console.log(`built ${out}  ${(html.length / 1024 / 1024).toFixed(2)} MB  modules=[${real.join(',')}]${dev ? ' (dev)' : ''}`);
